--
--   目的:
--     システムアカウント（人間の担当者ではない、通知・自動送信用の
--     アカウント）を判別できるようにする。
--     メンション候補や担当者一覧などで、実在の担当者と
--     システムアカウントを区別するために使用する。
--
--   Supabase ダッシュボード > SQL Editor で実行してください。
-- ================================================================

-- ----------------------------------------------------------------
-- 1. カラム追加
-- ----------------------------------------------------------------
ALTER TABLE profiles
  ADD COLUMN IF NOT EXISTS is_system boolean NOT NULL DEFAULT false;

-- ----------------------------------------------------------------
-- 2. コメント付与
-- ----------------------------------------------------------------
COMMENT ON COLUMN profiles.is_system IS
  'システムアカウント判別フラグ。true = 人間の担当者ではない通知用アカウント（自動送信・システム通知用）。false = 通常のユーザー／担当者。';

-- ----------------------------------------------------------------
-- 3. 「インフォ さん」をシステムアカウントに設定
--    ※ name 一致ではなく UUID 指定（同名アカウントの誤更新を防ぐため）
-- ----------------------------------------------------------------
UPDATE profiles
SET    is_system = true
WHERE  id = '7893dda8-bee1-4e6f-8cd4-3514ef5db2e4';

